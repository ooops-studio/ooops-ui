import {describe, expect, it, vi} from 'vitest'

import {addCalendarDays, addCalendarMonths, createCalendarController, getCalendarDays, parseCalendarDate} from '../src/calendar'

describe('calendar date arithmetic', () => {
	it('uses strict ISO calendar dates, Gregorian leap days and no time-zone conversions', () => {
		for (const date of ['2024-02-29', '0001-01-01', '0099-12-31', '2000-02-29', '9999-12-31'])
			expect(parseCalendarDate(date)?.toISOString().slice(0, 10)).toBe(date)
		for (const date of ['2023-02-29', '1900-02-29', '2026-04-31', '2026-00-10', '2026-13-01', '2026-01-00', '0000-01-01', '26-01-01', '2026-1-1', '2026-01-01T00:00:00Z', ''])
			expect(parseCalendarDate(date)).toBeNull()
		expect(addCalendarDays('2026-03-29', 1)).toBe('2026-03-30')
		expect(addCalendarDays('2024-02-28', 1)).toBe('2024-02-29')
		expect(addCalendarDays('2024-12-31', 1)).toBe('2025-01-01')
		expect(addCalendarMonths('2024-01-31', 1)).toBe('2024-02-29')
		expect(addCalendarMonths('2024-02-29', 12)).toBe('2025-02-28')
		expect(addCalendarMonths('2026-01-31', -1)).toBe('2025-12-31')
		expect(addCalendarDays('0001-01-01', -1)).toBe('0001-01-01')
		expect(addCalendarDays('9999-12-31', 1)).toBe('9999-12-31')
		expect(addCalendarMonths('0001-01-01', -1)).toBe('0001-01-01')
		expect(addCalendarMonths('9999-12-31', 1)).toBe('9999-12-31')
		expect(() => addCalendarDays('bad', 1)).toThrow(RangeError)
	})
	it('builds complete weeks with configurable week starts and finite year boundaries', () => {
		const monday = getCalendarDays('2026-10-21')
		expect(monday).toHaveLength(42)
		expect(monday[0]).toBe('2026-09-28')
		expect(getCalendarDays('2026-10-01', 0)[0]).toBe('2026-09-27')
		const early = getCalendarDays('0001-01-01', 0), late = getCalendarDays('9999-12-01')
		expect(early[0]).toBe('')
		expect(late.at(-1)).toBe('')
		expect(new Set(early.filter(Boolean)).size).toBe(early.filter(Boolean).length)
	})
})

describe('calendar controller', () => {
	it('selects single dates, bounds changes, formats labels and notifies without aliasing state', () => {
		const onChange = vi.fn(), onComplete = vi.fn(), onFocusDate = vi.fn()
		const calendar = createCalendarController({today: '2026-10-21', min: '2026-10-01', max: '2026-10-31', locale: 'en-US', onChange, onComplete, onFocusDate})
		expect(calendar.getState().focusedDate).toBe('2026-10-21')
		expect(calendar.formatDate('2026-10-21')).toBe('Wednesday, October 21, 2026')
		expect(calendar.formatMonth()).toBe('October 2026')
		expect(calendar.getWeekdays()[0]).toEqual({short: 'Mon', long: 'Monday'})
		expect(calendar.getDays()).toHaveLength(42)
		expect(calendar.isValid()).toBe(true)
		expect(calendar.select('bad')).toBe(false)
		expect(calendar.select('2026-09-30')).toBe(false)
		expect(calendar.select('2026-11-01')).toBe(false)
		expect(calendar.select('2026-10-23')).toBe(true)
		expect(onChange).toHaveBeenLastCalledWith({start: '2026-10-23', end: '2026-10-23'})
		expect(onComplete).toHaveBeenCalledOnce()
		onChange.mock.calls[0]![0].start = 'mutated'
		expect(calendar.getState().start).toBe('2026-10-23')
		calendar.focusDate('2027-01-01')
		expect(calendar.getState().focusedDate).toBe('2026-10-31')
		calendar.moveMonth(-2)
		expect(calendar.getState().focusedDate).toBe('2026-10-01')
		calendar.setValue({start: '2026-09-30', end: ''})
		expect(calendar.isValid()).toBe(false)
		calendar.configure({min: '2026-09-01', max: '2026-11-30', value: {start: '2026-10-10', end: ''}, disabled: true, firstDayOfWeek: 0})
		expect(calendar.getState().disabled).toBe(true)
		expect(calendar.select('2026-10-22')).toBe(false)
		expect(calendar.getWeekdays()[0]!.long).toBe('Sunday')
		calendar.configure({disabled: false, locale: 'el-GR'})
		expect(calendar.formatMonth()).toContain('2026')
		expect(calendar.isValid()).toBe(true)
		expect(onFocusDate).toHaveBeenCalledTimes(2)
	})
	it('completes ordered ranges in either direction and refuses disabled dates inside a range', () => {
		const onChange = vi.fn(), onComplete = vi.fn()
		const calendar = createCalendarController({range: true, today: '2026-10-21', isDateDisabled: (date) => date === '2026-10-25', onChange, onComplete})
		calendar.select('2026-10-23')
		expect(calendar.isValid()).toBe(false)
		expect(onComplete).not.toHaveBeenCalled()
		expect(calendar.select('2026-10-27')).toBe(false)
		expect(calendar.select('2026-10-25')).toBe(false)
		expect(calendar.select('2026-10-21')).toBe(true)
		expect(calendar.getState()).toMatchObject({start: '2026-10-21', end: '2026-10-23'})
		expect(calendar.isValid()).toBe(true)
		expect(onComplete).toHaveBeenCalledOnce()
		calendar.select('2026-10-28')
		calendar.select('2026-10-29')
		expect(calendar.getState()).toMatchObject({start: '2026-10-28', end: '2026-10-29'})
		calendar.setValue({start: '2026-10-30', end: '2026-10-29'})
		expect(calendar.isValid()).toBe(false)
		calendar.setValue({start: '', end: '2026-10-30'})
		expect(calendar.isValid()).toBe(false)
		const plain = createCalendarController({range: true})
		plain.select('2026-10-20'); plain.select('2026-10-20')
		expect(plain.isValid()).toBe(true)
	})
	it('supports arrow, week, month and year navigation with RTL and clamping', () => {
		const calendar = createCalendarController({today: '2024-02-29', firstDayOfWeek: 1})
		const key = (value: string, shiftKey = false) => {
			const event = {key: value, shiftKey, preventDefault: vi.fn()} as unknown as KeyboardEvent
			calendar.handleKeyDown(event)
			return event
		}
		key('ArrowRight'); expect(calendar.getState().focusedDate).toBe('2024-03-01')
		key('ArrowLeft'); expect(calendar.getState().focusedDate).toBe('2024-02-29')
		key('ArrowUp'); expect(calendar.getState().focusedDate).toBe('2024-02-22')
		key('ArrowDown'); expect(calendar.getState().focusedDate).toBe('2024-02-29')
		key('Home'); expect(calendar.getState().focusedDate).toBe('2024-02-26')
		key('End'); expect(calendar.getState().focusedDate).toBe('2024-03-03')
		key('PageUp'); expect(calendar.getState().focusedDate).toBe('2024-02-03')
		key('PageDown'); expect(calendar.getState().focusedDate).toBe('2024-03-03')
		key('PageUp', true); expect(calendar.getState().focusedDate).toBe('2023-03-03')
		key('PageDown', true); expect(calendar.getState().focusedDate).toBe('2024-03-03')
		calendar.configure({dir: 'rtl'})
		key('ArrowRight'); expect(calendar.getState().focusedDate).toBe('2024-03-02')
		key('ArrowLeft'); expect(calendar.getState().focusedDate).toBe('2024-03-03')
		key('Enter'); expect(calendar.getState().start).toBe('2024-03-03')
		key(' '); expect(calendar.getState().end).toBe('2024-03-03')
		expect(key('Tab').preventDefault).not.toHaveBeenCalled()
		for (const modifier of ['altKey', 'ctrlKey', 'metaKey']) {
			const event = {key: 'ArrowRight', [modifier]: true, preventDefault: vi.fn()} as unknown as KeyboardEvent
			calendar.handleKeyDown(event); expect(event.preventDefault).not.toHaveBeenCalled()
		}
		calendar.configure({disabled: true})
		expect(key('ArrowRight').preventDefault).not.toHaveBeenCalled()
	})
	it('fails fast for invalid configuration and cleans subscriptions on destroy', () => {
		for (const config of [{min: 'bad'}, {max: 'bad'}, {today: 'bad'}, {min: '2026-02-01', max: '2026-01-01'}, {firstDayOfWeek: -1}, {firstDayOfWeek: 7}, {firstDayOfWeek: 0.5}, {value: {start: 'bad', end: ''}}])
			expect(() => createCalendarController(config)).toThrow(RangeError)
		const calendar = createCalendarController()
		expect(parseCalendarDate(calendar.getState().focusedDate)).not.toBeNull()
		const listener = vi.fn(), unsubscribe = calendar.subscribe(listener)
		calendar.select('2026-10-21')
		expect(listener).toHaveBeenCalledTimes(2)
		unsubscribe()
		calendar.setValue({start: '', end: ''})
		expect(listener).toHaveBeenCalledTimes(2)
		expect(() => calendar.configure({max: 'bad'})).toThrow(RangeError)
		calendar.select('2026-10-22')
		expect(calendar.getState().start).toBe('2026-10-22')
		expect(() => calendar.setValue({start: '', end: 'bad'})).toThrow(RangeError)
		calendar.setValue({start: '2026-10-22', end: ''})
		expect(() => calendar.configure({range: true, value: {start: 'bad', end: ''}})).toThrow(RangeError)
		expect(calendar.isValid()).toBe(true)
		calendar.destroy()
		calendar.configure({disabled: true})
		calendar.focusDate('2026-10-23')
		calendar.setValue({start: '2026-10-23', end: ''})
		calendar.handleKeyDown({key: 'ArrowDown'} as KeyboardEvent)
		expect(calendar.select('2026-10-23')).toBe(false)
		expect(calendar.getState().start).toBe('2026-10-22')
	})
})
