import AxeBuilder from '@axe-core/playwright'
import {expect, test} from '@playwright/test'

export function registerCalendarCases(adapter: 'astro' | 'svelte') {
	test('date picker keyboard, month changes, focus return and native form data @critical', async({page}) => {
		await test.step('[FM-CALENDAR/keyboard-and-form]', async() => {
			const errors: string[] = []
			page.on('pageerror', (error) => errors.push(error.message))
			await page.goto('/calendar')
			await expect(page.locator('#ready')).toHaveText('ready')
			const input = page.getByLabel('Event date', {exact: true})
			const opener = page.getByRole('button', {name: 'Choose date, 2026-10-21', exact: true}).first()
			await opener.click()
			const calendar = page.getByRole('dialog', {name: 'October 2026'})
			const date = calendar.locator('[data-date="2026-10-21"]')
			await expect(date).toBeFocused()
			await expect(calendar.locator('[data-date][tabindex="0"]')).toHaveCount(1)
			await page.keyboard.press('ArrowRight')
			await expect(calendar.locator('[data-date="2026-10-22"]')).toBeFocused()
			await page.keyboard.press('PageDown')
			await expect(page.getByRole('dialog', {name: 'November 2026'})).toBeVisible()
			await expect(page.locator('dialog[open] [data-date="2026-11-22"]')).toBeFocused()
			await page.keyboard.press('Enter')
			await expect(page.locator('dialog[open]')).toHaveCount(0)
			await expect(input).toHaveValue('2026-11-22')
			await expect(page.getByRole('button', {name: 'Choose date, 2026-11-22'})).toBeFocused()
			await expect(page.locator('#changes')).toHaveText('1')
			await page.getByRole('button', {name: 'Submit dates'}).click()
			await expect(page.locator('#form-values')).toContainText('"date":"2026-11-22"')
			await page.getByRole('button', {name: 'Reset dates'}).click()
			await expect(input).toHaveValue('2026-10-21')
			await expect(page.locator('#changes')).toHaveText('1')
			expect(errors).toEqual([])
		})
	})
	test('date range orders reverse selections, blocks unavailable spans and validates typed input @critical', async({page}) => {
		await test.step('[FM-CALENDAR/range-and-reset]', async() => {
			await page.goto('/calendar')
			await expect(page.locator('#ready')).toHaveText('ready')
			const group = page.getByRole('group', {name: 'Travel dates'})
			await group.getByRole('button', {name: 'Choose date', exact: true}).click()
			const calendar = page.locator('dialog[open]')
			await calendar.locator('[data-date="2026-10-23"]').click()
			await expect(calendar).toBeVisible()
			await expect(calendar.locator('[data-date="2026-10-23"]')).toBeFocused()
			await calendar.locator('[data-date="2026-10-27"]').click()
			await expect(group.getByLabel('End date')).toHaveValue('')
			await expect(calendar.locator('[data-date="2026-10-25"]')).toHaveAttribute('aria-disabled', 'true')
			await calendar.locator('[data-date="2026-10-21"]').click()
			await expect(calendar).not.toBeVisible()
			await expect(group.getByLabel('Start date')).toHaveValue('2026-10-21')
			await expect(group.getByLabel('End date')).toHaveValue('2026-10-23')
			await page.getByRole('button', {name: 'Submit dates'}).click()
			await expect(page.locator('#form-values')).toContainText('"trip-start":"2026-10-21"')
			await expect(page.locator('#form-values')).toContainText('"trip-end":"2026-10-23"')
			await group.getByLabel('End date').fill('2026-10-20')
			expect(await group.getByLabel('End date').evaluate((node: HTMLInputElement) => node.validity.valid)).toBe(false)
			await expect(group.getByLabel('End date')).toHaveAttribute('aria-invalid', 'true')
			await expect(group.getByLabel('End date')).toHaveAttribute('aria-describedby', 'trip-error')
			await expect(group.getByRole('alert')).toContainText('Choose an available date')
			await group.getByLabel('End date').fill('2026-10-23')
			expect(await group.getByLabel('End date').evaluate((node: HTMLInputElement) => node.validity.valid)).toBe(true)
			await expect(group.getByLabel('End date')).not.toHaveAttribute('aria-invalid')
			await page.getByRole('button', {name: 'Toggle reset prevention'}).click()
			await page.getByRole('button', {name: 'Reset dates'}).click()
			await expect(group.getByLabel('Start date')).toHaveValue('2026-10-21')
			await page.getByRole('button', {name: 'Toggle reset prevention'}).click()
			await page.getByRole('button', {name: 'Reset dates'}).click()
			await expect(group.getByLabel('Start date')).toHaveValue('')
			await expect(group.getByLabel('End date')).toHaveValue('')
		})
	})
	test('calendar stays inside the viewport, escapes and exposes an accessible grid @critical', async({page}) => {
		await test.step('[FM-CALENDAR/accessible-layout]', async() => {
			await page.setViewportSize({width: 393, height: 852})
			await page.goto('/calendar')
			await expect(page.locator('#ready')).toHaveText('ready')
			await page.getByRole('button', {name: 'Choose date, 2026-10-21', exact: true}).first().click()
			const calendar = page.locator('dialog[open]')
			expect((await new AxeBuilder({page}).include('dialog[open]').analyze()).violations).toEqual([])
			const box = await calendar.boundingBox()
			expect(box!.x).toBeGreaterThanOrEqual(16)
			expect(box!.x + box!.width).toBeLessThanOrEqual(377)
			expect(box!.height).toBeLessThanOrEqual(852)
			await page.keyboard.press('Escape')
			await expect(calendar).not.toBeVisible()
			await expect(page.getByRole('button', {name: 'Choose date, 2026-10-21', exact: true}).first()).toBeFocused()
			await expect(page.getByLabel('Locked date', {exact: true})).toBeDisabled()
			await expect(page.getByLabel('Read only date', {exact: true})).toHaveAttribute('readonly', '')
			if (adapter === 'svelte') {
				await page.getByRole('button', {name: 'Set external date', exact: true}).click()
				await expect(page.getByLabel('Event date', {exact: true})).toHaveValue('2026-11-30')
				await page.getByRole('button', {name: 'Toggle disabled date'}).click()
				await expect(page.getByLabel('Event date', {exact: true})).toBeDisabled()
			}
		})
	})
	test('native dates work without JavaScript', async({browser, baseURL}) => {
		await test.step('[FM-CALENDAR/no-js]', async() => {
			const context = await browser.newContext({javaScriptEnabled: false})
			const page = await context.newPage()
			await page.goto(`${baseURL}/calendar`)
			await expect(page.getByLabel('Event date', {exact: true})).toHaveValue('2026-10-21')
			await page.getByLabel('Event date', {exact: true}).fill('2026-12-01')
			await expect(page.getByLabel('Event date', {exact: true})).toHaveValue('2026-12-01')
			await expect(page.getByRole('button', {name: /^Choose date/})).toHaveCount(0)
			await context.close()
		})
	})
}
