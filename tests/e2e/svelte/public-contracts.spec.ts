import {expect, test} from '@playwright/test'

import {expectNoAxeViolations, watchRuntimeErrors} from '../support'

test('@critical native forwarding, Field associations, refs, disabled chips and scoped CSS', async({page}, info) => {
	const healthy = watchRuntimeErrors(page)
	await page.goto('/contracts'); await expect(page.locator('#ready')).toHaveText('ready')
	const input = page.getByRole('textbox', {name: 'Contact email'})
	await expect(input).toHaveAttribute('aria-describedby', 'outside-help email-field-description email-field-error')
	await expect(input).toHaveAttribute('aria-invalid', 'true'); await expect(input).toHaveAttribute('maxlength', '30')
	await page.getByRole('button', {name: 'Focus email'}).click(); await expect(input).toBeFocused()
	await input.fill('a@example.test'); await input.press('Tab')
	await expect(page.locator('#event-counts')).toHaveText('1|1|1|1')
	expect(await input.evaluate((el) => (el as HTMLInputElement).form?.id)).toBe('native-form')
	await expect(page.getByRole('textbox', {name: 'Private notes'})).toHaveAttribute('minlength', '2')
	await expect(page.getByRole('radiogroup', {name: 'Theme'})).toBeVisible()
	await expect(page.getByRole('button', {name: 'Remove Alpha'})).toBeDisabled()
	await page.getByRole('button', {name: 'Toggle tags disabled'}).click(); await page.getByRole('button', {name: 'Remove Alpha'}).click()
	await expect(page.locator('#tags-state')).toHaveText('[]')
	expect(await page.locator('#foreign-content').evaluate((el) => getComputedStyle(el).position)).toBe('static')
	expect(await page.locator('#foreign-track').evaluate((el) => getComputedStyle(el).position)).toBe('static')
	await page.getByRole('tab', {name: 'Second tab', exact: true}).click()
	await expect(page.locator('#external-one')).toBeHidden(); await expect(page.locator('#external-two')).toBeVisible()
	await page.getByRole('button', {name: 'Button two', exact: true}).click(); await expect(page.getByRole('button', {name: 'Button two', exact: true})).toHaveAttribute('aria-current', 'page')
	await page.getByRole('button', {name: 'Toggle email field'}).click(); await expect(page.locator('#reference-state')).toHaveText('none')
	await expectNoAxeViolations(page, info); healthy()
})

test('@critical external anchors, nested menus, close guards, modal focus and async error recovery', async({page}) => {
	const healthy = watchRuntimeErrors(page)
	await page.goto('/contracts'); await expect(page.locator('#ready')).toHaveText('ready')
	const pop = page.getByRole('button', {name: 'External popover', exact: true})
	await pop.click(); await expect(page.locator('#custom-portal #external-pop-panel')).toBeVisible()
	expect(await page.locator('#external-pop-panel').evaluate((el) => el.getBoundingClientRect().width)).toBeGreaterThanOrEqual(await pop.evaluate((el) => el.getBoundingClientRect().width))
	await page.keyboard.press('Escape'); await expect(page.locator('#external-pop-panel')).toBeVisible()
	await page.getByRole('button', {name: 'Toggle close permission'}).click(); await page.keyboard.press('Escape'); await expect(page.locator('#external-pop-panel')).toBeHidden()
	await page.getByRole('button', {name: 'External menu', exact: true}).click()
	await page.getByRole('menuitemcheckbox', {name: 'Checked option'}).click(); await expect(page.locator('#menu-selection')).toHaveText('checked:true')
	await expect(page.getByRole('menuitemcheckbox', {name: 'Checked option'})).toHaveAttribute('aria-checked', 'true')
	await page.getByRole('menuitem', {name: 'Level one', exact: true}).click(); await page.getByRole('menuitem', {name: 'Level two', exact: true}).click(); await page.getByRole('menuitem', {name: 'Deep action', exact: true}).click()
	await expect(page.locator('#menu-selection')).toHaveText('leaf:undefined')
	await page.getByRole('button', {name: 'Toggle close permission'}).click()
	await page.getByRole('button', {name: 'Open guarded modal'}).click(); await expect(page.getByRole('textbox', {name: 'Modal input'})).toBeFocused()
	await page.keyboard.press('Escape'); await expect(page.getByRole('dialog', {name: 'Guarded modal'})).toBeVisible()
	await page.getByRole('dialog', {name: 'Guarded modal'}).evaluate((el) => (el as HTMLDialogElement).close())
	await expect(page.getByRole('dialog', {name: 'Guarded modal'})).toBeVisible()
	await page.getByRole('button', {name: 'Attempt controlled close'}).click(); await expect(page.getByRole('dialog', {name: 'Guarded modal'})).toBeVisible()
	await page.getByRole('button', {name: 'Close dialog', exact: true}).click(); await expect(page.getByRole('dialog', {name: 'Guarded modal'})).toBeVisible()
	await page.getByRole('button', {name: 'Allow modal close'}).click(); await page.keyboard.press('Escape')
	await expect(page.getByRole('dialog', {name: 'Guarded modal'})).toBeHidden(); await expect(page.locator('#modal-trigger')).toBeFocused()
	await page.getByRole('button', {name: 'Open confirmation'}).click(); const save = page.getByRole('button', {name: 'Confirm', exact: true})
	await save.click(); await expect(save).toBeDisabled(); await expect(page.locator('#save-state')).toHaveText('1|1'); await expect(save).toBeEnabled()
	await expect(page.getByRole('dialog', {name: 'Save changes'})).toBeVisible(); healthy()
})
