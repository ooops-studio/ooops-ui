import {expect, test} from '@playwright/test'

import {expectNoAxeViolations, watchRuntimeErrors} from '../support'

test('@critical migration callbacks, disabled projections, readonly, reset and accordion configuration', async({page}, testInfo) => {
	const assertNoErrors = watchRuntimeErrors(page)
	await page.goto('/regressions')
	await expect(page.locator('#hydration-state')).toHaveText('hydrated')
	await page.getByRole('button', {name: 'Set parent values'}).click()
	await page.locator('#reg-input').fill('A')
	await page.locator('#reg-textarea').fill('A')
	await expect(page.locator('#text-events')).toHaveText('["A"]')
	await expect(page.locator('#area-events')).toHaveText('["A"]')
	await page.getByRole('button', {name: 'Serialize controls'}).click()
	await expect(page.locator('#projection-output')).toHaveText('[]')
	await page.getByRole('button', {name: 'Toggle disabled'}).click()
	await page.getByRole('button', {name: 'Serialize controls'}).click()
	await expect(page.locator('#projection-output')).toHaveText('[["country","a"],["tags[]","a"],["view","a"],["volume[]","20"],["volume[]","80"]]')
	await page.getByRole('button', {name: 'Toggle disabled'}).click()
	await page.getByRole('button', {name: 'Serialize controls'}).click()
	await expect(page.locator('#projection-output')).toHaveText('[]')
	const readonly = page.getByRole('region', {name: 'Readonly clear'})
	await expect(readonly.getByRole('button', {name: 'Clear', exact: true})).toBeDisabled()
	await expect(page.locator('#reg-readonly')).toHaveValue('Locked')
	await page.getByRole('button', {name: 'Toggle readonly'}).click()
	await readonly.getByRole('button', {name: 'Clear', exact: true}).click()
	await expect(page.locator('#reg-readonly')).toHaveValue('')
	await page.getByRole('radiogroup', {name: 'Reset plan'}).getByLabel('Beta').check()
	await page.locator('#reg-reset-segments').getByRole('radio', {name: 'Beta'}).click()
	await expect(page.locator('#choice-bindings')).toHaveText('b|b')
	await page.getByRole('button', {name: 'Reset choices'}).click()
	await expect(page.locator('#choice-bindings')).toHaveText('a|a')
	await expect(page.getByRole('radiogroup', {name: 'Reset plan'}).getByLabel('Alpha')).toBeChecked()
	await page.getByRole('button', {name: 'Toggle accordion mode'}).click()
	await page.getByRole('button', {name: 'First regression section'}).click()
	await page.getByRole('button', {name: 'Second regression section'}).click()
	await expect(page.locator('#accordion-binding')).toHaveText('["first","second"]')
	await page.getByRole('button', {name: 'Toggle accordion mode'}).click()
	await page.getByRole('button', {name: 'Toggle collapsible'}).click()
	await page.getByRole('button', {name: 'First regression section'}).click()
	await expect(page.locator('#accordion-binding')).toHaveText('["first"]')
	await expectNoAxeViolations(page, testInfo)
	assertNoErrors()
})

test('@critical checked defaults exist without JavaScript', async({browser}) => {
	const context = await browser.newContext({javaScriptEnabled: false})
	try {
		const page = await context.newPage()
		await page.goto('http://127.0.0.1:4393/regressions')
		await expect(page.locator('#reg-checked')).toBeChecked()
		await expect(page.locator('#reg-switch')).toBeChecked()
		await expect(page.locator('#reg-switch')).toHaveAttribute('role', 'switch')
		await expect(page.locator('#reg-checked')).toHaveAttribute('checked', '')
	} finally { await context.close() }
})

test('@critical native checkbox edits survive delayed hydration', async({page}) => {
	const assertNoErrors = watchRuntimeErrors(page)
	let release = () => {}
	const gate = new Promise<void>((resolve) => { release = resolve })
	await page.route('**/*.js', async(route) => { await gate; await route.continue() })
	try {
		await page.goto('/regressions', {waitUntil: 'domcontentloaded'})
		await expect(page.locator('#hydration-state')).toHaveText('server')
		await page.getByText('Initially checked', {exact: true}).click()
		await page.getByText('Initially enabled', {exact: true}).click()
		await expect(page.locator('#reg-checked')).not.toBeChecked()
		await expect(page.locator('#reg-switch')).not.toBeChecked()
		release()
		await expect(page.locator('#hydration-state')).toHaveText('hydrated')
		await expect(page.locator('#check-bindings')).toHaveText('false|false')
		await expect(page.locator('#reg-checked')).not.toBeChecked()
		await expect(page.locator('#reg-switch')).not.toBeChecked()
		await page.getByRole('button', {name: 'Reset checked defaults'}).click()
		await expect(page.locator('#check-bindings')).toHaveText('true|true')
		assertNoErrors()
	} finally { release() }
})
