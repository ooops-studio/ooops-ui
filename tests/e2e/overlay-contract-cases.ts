import {expect, test} from '@playwright/test'

import {expectNoAxeViolations, watchRuntimeErrors} from './support'

export function registerOverlayContractCases() {
	test.beforeEach(async({page}) => {
		await page.goto('/overlays')
		await expect(page.locator('html')).toHaveAttribute('data-overlay-ready', 'true')
	})
	test('@critical owned native modal portals, child menus and one-level Escape', async({page}, info) => {
		const healthy = watchRuntimeErrors(page)
		const opener = page.getByRole('button', {name: 'Open overlay workspace'})
		await opener.click()
		const modal = page.getByRole('dialog', {name: 'Overlay workspace', exact: true})
		await expect(modal).toBeVisible()
		await test.step('[FM-OVERLAY-CONTRACTS/native-portals]', async() => {
			await page.getByRole('button', {name: 'Nested details', exact: true}).click()
			const popup = page.getByRole('dialog', {name: 'Nested details', exact: true})
			expect(await popup.evaluate((el) => Boolean(el.closest('dialog[open]')))).toBe(true)
			await popup.getByRole('button', {name: 'Nested action'}).click()
			await expect(page.getByLabel('Action', {exact: true})).toHaveText('popover')
			await page.keyboard.press('Escape'); await expect(popup).toBeHidden()
			await expect(modal).toBeVisible()
		})
		await test.step('[FM-OVERLAY-CONTRACTS/submenu-escape]', async() => {
			await page.getByRole('button', {name: 'Nested actions', exact: true}).click()
			const owner = page.getByRole('menuitem', {name: 'More', exact: true})
			await owner.press('ArrowRight')
			const first = page.getByRole('menuitem', {name: 'First child'})
			await expect(first).toBeFocused(); await first.press('ArrowUp')
			await expect(page.getByRole('menuitem', {name: 'Last child'})).toBeFocused()
			await page.keyboard.press('Escape'); await expect(owner).toBeFocused()
			await page.keyboard.press('Escape')
			await expect(page.getByRole('button', {name: 'Nested actions', exact: true})).toBeFocused()
			await expect(modal).toBeVisible()
		})
		await expectNoAxeViolations(page, info)
		await page.keyboard.press('Escape'); await expect(modal).toBeHidden(); await expect(opener).toBeFocused()
		healthy()
	})

	test('@critical outside focus dismisses a menu branch while hover help keeps user focus', async({page}) => {
		const healthy = watchRuntimeErrors(page)
		await page.getByRole('button', {name: 'Open overlay workspace'}).click()
		await test.step('[FM-OVERLAY-CONTRACTS/outside-branch]', async() => {
			await page.getByRole('button', {name: 'Nested actions', exact: true}).click()
			await page.getByRole('menuitem', {name: 'More', exact: true}).press('ArrowRight')
			await page.getByRole('textbox', {name: 'Modal text'}).focus()
			await expect(page.getByRole('menu', {name: 'Nested actions', exact: true})).toBeHidden()
			await expect(page.getByRole('menu', {name: 'More', exact: true})).toBeHidden()
		})
		await test.step('[FM-OVERLAY-CONTRACTS/hover-focus]', async() => {
			const input = page.getByRole('textbox', {name: 'Modal text'})
			await page.getByRole('button', {name: 'Context help'}).hover()
			const tip = page.getByRole('tooltip')
			await expect(tip).toBeVisible(); await expect(tip).toHaveText('Contextual instructions'); await tip.hover(); await page.waitForTimeout(140)
			await expect(tip).toBeVisible(); await expect(input).toBeFocused()
			await page.keyboard.press('Escape'); await expect(tip).toBeHidden(); await expect(input).toBeFocused()
		})
		healthy()
	})

	test('@critical non-modal focus contract and async confirm failure recovery', async({page}, info) => {
		const healthy = watchRuntimeErrors(page)
		await test.step('[FM-OVERLAY-CONTRACTS/non-modal]', async() => {
			const opener = page.getByRole('button', {name: 'Open non-modal drawer'})
			await opener.focus(); await opener.press('Enter')
			const drawer = page.getByRole('region', {name: 'Non-modal drawer', exact: true})
			await expect(drawer).toBeVisible(); await expect(opener).toBeFocused()
			await expect(drawer).not.toHaveAttribute('aria-modal', 'true')
			const close = page.getByRole('button', {name: 'Close drawer'})
			await close.focus(); await close.press(info.project.name.includes('webkit') ? 'Alt+Tab' : 'Tab')
			await expect(page.getByRole('button', {name: 'After drawer'})).toBeFocused()
			await page.getByRole('textbox', {name: 'Drawer note'}).press('Escape')
			await expect(drawer).toBeHidden()
		})
		await test.step('[FM-OVERLAY-CONTRACTS/async-confirm]', async() => {
			const opener = page.getByRole('button', {name: 'Open confirmation'})
			await opener.click()
			const dialog = page.getByRole('dialog', {name: 'Save changes'})
			const confirm = dialog.getByRole('button', {name: 'Confirm', exact: true})
			await dialog.getByRole('button', {name: 'Decline next confirmation'}).click()
			await confirm.click(); await expect(confirm).toBeEnabled()
			await expect(dialog.getByRole('alert')).toHaveText('Review your changes')
			await expect(page.getByLabel('Requests', {exact: true})).toHaveText('0')
			await confirm.click(); await expect(confirm).toBeDisabled()
			await expect(dialog).toHaveAttribute('aria-busy', 'true')
			await page.keyboard.press('Escape'); await expect(dialog).toBeVisible()
			await expect(page.getByLabel('Requests', {exact: true})).toHaveText('1')
			await dialog.getByRole('button', {name: 'Reject request'}).click()
			await expect(dialog.getByRole('alert')).toHaveText('Request failed')
			await expect(confirm).toBeEnabled()
			await page.screenshot({path: info.outputPath('async-error-recovery.png')})
			await confirm.click(); await dialog.getByRole('button', {name: 'Resolve request'}).click()
			await expect(dialog).toBeHidden(); await expect(opener).toBeFocused()
			await expect(page.getByLabel('Requests', {exact: true})).toHaveText('2')
		})
		healthy()
	})
}
